export function getBadgeTranslation(
  badge
) {
  const translation =
    badgeTranslations[
      badge.id
    ]

  return {
    name_fr:
      translation?.name_fr ??
      badge.name_en,

    description_fr:
      translation?.description_fr ??
      'Description française non disponible.',

    source:
      translation?.source ??
      null,

    status:
      translation?.status ??
      'unknown',
  }
}

